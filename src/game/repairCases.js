export const PARADE_STAMP_TARGET = 4

export function countFestivalRepairs(records) {
  return REPAIR_CASES.filter(item => records?.[item.id]).length
}

// 기준 문서: 개막 퍼레이드(스탬프 4개 이상이면 열림)를 마치면 정식 정비사가 되고 마이룸 정비 작업실이 열린다
export function hasRemoteRepairLicense(records) {
  return Boolean(records?.[PARADE.id])
}

// 지금까지 고친 사건에서 해금한 부품
export function ownedParts(records) {
  return REPAIR_CASES.filter(item => records?.[item.id]).map(item => item.part)
}

export const isTarget = (spec, value) => Array.isArray(spec.target) ? spec.target.includes(value) : value === spec.target

export function trialResult(repairCase, settings, index) {
  const keys = repairCase.testControls?.[index] ?? Object.keys(repairCase.controls)
  return keys.every(key => isTarget(repairCase.controls[key], settings[key]))
}
