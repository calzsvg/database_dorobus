// 고장 수사대 사건 데이터. 기준 문서: 도로랜드_프롬프트 (사건별 비공개 정보, 단서 공개 규칙, 힌트, 정답 판정, 대사)
// 단서 종류: 관찰(직접 보기), 질문(NPC에게 직접 묻기, 그 NPC의 증언), 점검(도구로 재기), 기록(기록 확인)
const clue = (id, type, label, fact, npc, after) => ({ id, type, label, fact, ...(npc ? { npc } : {}), ...(after ? { after } : {}) })
const ask = (id, npc, label, fact, after) => clue(id, '질문', label, fact, npc, after)
// after: 답을 바로 알려 줄 수 있는 질문과 점검은 관련 단서를 먼저 확인하거나 ‘막혔어, 도와줘’를 눌러야 버튼이 나타난다
const later = (c, ...after) => ({ ...c, after })
// target: 정답 값 하나 또는 허용되는 값 목록. parts: 선택지마다 필요한 부품(퍼레이드)
const control = (label, options, initial, target, parts) => ({ label, options, initial, target, ...(parts ? { parts } : {}) })
// 힌트: clues 중 하나라도 이미 확인했으면 그 힌트는 건너뛴다
const hint = (text, ...clues) => ({ text, clues })
// 오답 가설: 해당 단서를 아직 안 봤으면 확인하도록(ask), 이미 봤으면 그 단서로 반박(refute)
const wrong = (re, clueId, askText, refute) => ({ re, clue: clueId, ask: askText, refute })

